create table company_profile (
    id bigint generated by default as identity primary key,
    ruc varchar(11) not null unique,
    legal_name varchar(200) not null,
    trade_name varchar(160) not null,
    fiscal_address varchar(300),
    ubigeo varchar(6),
    website varchar(180),
    currency_code varchar(3) not null default 'PEN',
    timezone varchar(60) not null default 'America/Lima',
    active boolean not null default true
);

create table branch (
    id bigint generated by default as identity primary key,
    company_id bigint not null references company_profile(id),
    code varchar(10) not null,
    name varchar(120) not null,
    address varchar(300),
    ubigeo varchar(6),
    active boolean not null default true,
    unique (company_id, code)
);

create table document_series (
    id bigint generated by default as identity primary key,
    branch_id bigint not null references branch(id),
    document_type varchar(2) not null,
    series varchar(4) not null,
    next_number bigint not null default 1,
    active boolean not null default true,
    version bigint not null default 0,
    unique (document_type, series)
);

create table customer (
    id bigint generated by default as identity primary key,
    document_type varchar(2) not null,
    document_number varchar(20) not null,
    legal_name varchar(220) not null,
    email varchar(254),
    address varchar(300),
    active boolean not null default true,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    unique (document_type, document_number)
);

create table product (
    id bigint generated by default as identity primary key,
    sku varchar(60) not null unique,
    name varchar(220) not null,
    unit_code varchar(3) not null,
    igv_affectation_code varchar(2) not null default '10',
    sale_price numeric(14, 2) not null,
    stock_controlled boolean not null default true,
    active boolean not null default true,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp
);

create table sale (
    id bigint generated by default as identity primary key,
    branch_id bigint not null references branch(id),
    customer_id bigint not null references customer(id),
    document_type varchar(2) not null,
    series varchar(4) not null,
    number bigint not null,
    issue_date date not null,
    currency_code varchar(3) not null default 'PEN',
    status varchar(30) not null,
    subtotal numeric(14, 2) not null,
    tax_amount numeric(14, 2) not null,
    total numeric(14, 2) not null,
    created_by bigint not null references app_user(id),
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    unique (document_type, series, number)
);

create table sale_line (
    id bigint generated by default as identity primary key,
    sale_id bigint not null references sale(id),
    line_number integer not null,
    product_id bigint references product(id),
    description varchar(500) not null,
    unit_code varchar(3) not null,
    quantity numeric(14, 4) not null,
    unit_value numeric(14, 6) not null,
    tax_amount numeric(14, 2) not null,
    line_total numeric(14, 2) not null,
    unique (sale_id, line_number)
);

create table electronic_document (
    id bigint generated by default as identity primary key,
    sale_id bigint not null references sale(id),
    document_type varchar(2) not null,
    series varchar(4) not null,
    number bigint not null,
    status varchar(30) not null,
    xml_sha256 varchar(64),
    xml_object_key varchar(500),
    cdr_object_key varchar(500),
    provider_ticket varchar(180),
    error_code varchar(60),
    error_message varchar(1000),
    sent_at timestamp with time zone,
    accepted_at timestamp with time zone,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    unique (document_type, series, number)
);

create table inventory_movement (
    id bigint generated by default as identity primary key,
    branch_id bigint not null references branch(id),
    product_id bigint not null references product(id),
    movement_type varchar(30) not null,
    quantity numeric(14, 4) not null,
    reference_type varchar(40),
    reference_id varchar(120),
    actor_user_id bigint not null references app_user(id),
    occurred_at timestamp with time zone not null default current_timestamp,
    notes varchar(500)
);

create index idx_sale_issue_date on sale(issue_date);
create index idx_sale_customer on sale(customer_id);
create index idx_electronic_document_status on electronic_document(status);
create index idx_inventory_movement_product_date on inventory_movement(product_id, occurred_at);

