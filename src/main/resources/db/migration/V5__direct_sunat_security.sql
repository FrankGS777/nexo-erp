alter table fiscal_configuration add column sol_password_reference varchar(500);
alter table fiscal_configuration add column certificate_password_reference varchar(500);

alter table electronic_document add column signed_xml_object_key varchar(500);
alter table electronic_document add column signed_xml_sha256 varchar(64);

create table fiscal_submission_attempt (
    id bigint generated by default as identity primary key,
    electronic_document_id bigint not null references electronic_document(id),
    idempotency_key varchar(160) not null unique,
    status varchar(30) not null,
    request_sha256 varchar(64) not null,
    response_sha256 varchar(64),
    provider_code varchar(40) not null,
    provider_ticket varchar(180),
    error_code varchar(80),
    error_message varchar(1000),
    started_at timestamp with time zone not null default current_timestamp,
    completed_at timestamp with time zone
);

create index idx_fiscal_attempt_document
    on fiscal_submission_attempt(electronic_document_id, started_at);
