alter table customer add column credit_limit numeric(14,2) not null default 0;
alter table customer add column credit_days integer not null default 0;
alter table customer add column credit_approved_by bigint references app_user(id);
alter table product add column net_reference_price numeric(14,6);
alter table product add column price_origin varchar(30) not null default 'PENDING';
alter table product add column volume_litres numeric(10,3);

create table commercial_import (
 id bigint generated by default as identity primary key,
 fingerprint varchar(64) not null unique,
 imported_at timestamp with time zone not null default current_timestamp,
 summary text not null
);
create table price_evidence (
 id bigint generated by default as identity primary key,
 source_key varchar(180) not null unique,
 customer_id bigint not null references customer(id),
 product_id bigint references product(id),
 invoice_number varchar(40) not null,
 issue_date date not null,
 description varchar(500) not null,
 quantity numeric(14,4) not null,
 net_unit_price numeric(14,6) not null,
 line_net numeric(14,2) not null,
 tax_rate numeric(8,4),
 declared_unit_price numeric(14,6),
 source_hash varchar(64) not null,
 observation varchar(500)
);
create table customer_price (
 customer_id bigint not null references customer(id),
 product_id bigint not null references product(id),
 net_price numeric(14,6) not null check (net_price > 0),
 origin varchar(30) not null,
 evidence_id bigint references price_evidence(id),
 approved boolean not null default false,
 approved_by bigint references app_user(id),
 updated_at timestamp with time zone not null default current_timestamp,
 primary key(customer_id, product_id)
);
create table import_issue (
 id bigint generated by default as identity primary key,
 source_key varchar(220) not null unique,
 description varchar(1000) not null
);
create table commercial_order (
 id bigint generated by default as identity primary key,
 reference varchar(36) not null unique,
 customer_id bigint not null references customer(id),
 seller_id bigint not null references app_user(id),
 status varchar(30) not null default 'DRAFT',
 valid_until date not null,
 requested_date date,
 promised_date date,
 delivery_address varchar(300),
 payment_condition varchar(10) not null default 'CONTADO',
 notes varchar(1000),
 acceptance varchar(500),
 subtotal numeric(14,2) not null default 0,
 tax_amount numeric(14,2) not null default 0,
 total numeric(14,2) not null default 0,
 created_at timestamp with time zone not null default current_timestamp,
 updated_at timestamp with time zone not null default current_timestamp,
 version bigint not null default 0
);
create table commercial_order_line (
 id bigint generated by default as identity primary key,
 order_id bigint not null references commercial_order(id),
 product_id bigint not null references product(id),
 description varchar(500) not null,
 quantity numeric(14,4) not null check(quantity > 0),
 dispatched_quantity numeric(14,4) not null default 0,
 net_price numeric(14,6) not null check(net_price > 0),
 tax_rate numeric(6,3) not null,
 price_origin varchar(30) not null,
 price_approved boolean not null,
 unique(order_id, product_id),
 check(dispatched_quantity >= 0 and dispatched_quantity <= quantity)
);
create table commercial_dispatch (
 id bigint generated by default as identity primary key,
 order_id bigint not null references commercial_order(id),
 sale_id bigint not null unique references sale(id),
 request_key varchar(36) not null unique,
 status varchar(30) not null default 'PREPARED',
 guide_number varchar(40),
 guide_status varchar(30) not null default 'PENDING',
 transport_mode varchar(20),
 carrier_ruc varchar(11),
 vehicle_plate varchar(15),
 departure_address varchar(300),
 arrival_address varchar(300),
 transport_date date,
 created_by bigint not null references app_user(id),
 created_at timestamp with time zone not null default current_timestamp,
 departed_at timestamp with time zone
);
create table commercial_dispatch_line (
 dispatch_id bigint not null references commercial_dispatch(id),
 order_line_id bigint not null references commercial_order_line(id),
 quantity numeric(14,4) not null check(quantity > 0),
 primary key(dispatch_id, order_line_id)
);
create index idx_customer_seller on customer(assigned_seller_id);
create index idx_commercial_order_customer on commercial_order(customer_id,status);
create index idx_price_evidence_lookup on price_evidence(customer_id,product_id,issue_date);
