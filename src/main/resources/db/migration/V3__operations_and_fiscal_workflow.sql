alter table sale add column payment_status varchar(20) not null default 'PENDING';
alter table sale add column payment_method varchar(30);
alter table sale add column notes varchar(500);

alter table inventory_movement add column lot_number varchar(80);
alter table inventory_movement add column expiration_date date;

create table supplier (
    id bigint generated by default as identity primary key,
    document_type varchar(2) not null default '6',
    document_number varchar(20) not null,
    legal_name varchar(220) not null,
    email varchar(254),
    phone varchar(40),
    address varchar(300),
    active boolean not null default true,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    unique (document_type, document_number)
);

create table purchase (
    id bigint generated by default as identity primary key,
    branch_id bigint not null references branch(id),
    supplier_id bigint not null references supplier(id),
    supplier_document_type varchar(2) not null,
    supplier_series varchar(20),
    supplier_number varchar(30) not null,
    issue_date date not null,
    currency_code varchar(3) not null default 'PEN',
    status varchar(20) not null default 'RECEIVED',
    subtotal numeric(14, 2) not null,
    tax_amount numeric(14, 2) not null,
    total numeric(14, 2) not null,
    created_by bigint not null references app_user(id),
    created_at timestamp with time zone not null default current_timestamp,
    notes varchar(500),
    unique (supplier_id, supplier_document_type, supplier_series, supplier_number)
);

create table purchase_line (
    id bigint generated by default as identity primary key,
    purchase_id bigint not null references purchase(id),
    line_number integer not null,
    product_id bigint not null references product(id),
    description varchar(500) not null,
    quantity numeric(14, 4) not null,
    unit_cost numeric(14, 6) not null,
    tax_amount numeric(14, 2) not null,
    line_total numeric(14, 2) not null,
    lot_number varchar(80),
    expiration_date date,
    unique (purchase_id, line_number)
);

create table payment_record (
    id bigint generated by default as identity primary key,
    sale_id bigint not null references sale(id),
    paid_at timestamp with time zone not null default current_timestamp,
    amount numeric(14, 2) not null,
    method varchar(30) not null,
    reference varchar(120),
    registered_by bigint not null references app_user(id)
);

create table adjustment_document (
    id bigint generated by default as identity primary key,
    original_sale_id bigint not null references sale(id),
    document_type varchar(2) not null,
    series varchar(4) not null,
    number bigint not null,
    reason_code varchar(2) not null,
    reason varchar(500) not null,
    issue_date date not null,
    currency_code varchar(3) not null default 'PEN',
    subtotal numeric(14, 2) not null,
    tax_amount numeric(14, 2) not null,
    total numeric(14, 2) not null,
    status varchar(30) not null default 'DRAFT',
    created_by bigint not null references app_user(id),
    created_at timestamp with time zone not null default current_timestamp,
    unique (document_type, series, number)
);

alter table electronic_document alter column sale_id drop not null;
alter table electronic_document add column adjustment_id bigint references adjustment_document(id);

create table electronic_document_event (
    id bigint generated by default as identity primary key,
    electronic_document_id bigint not null references electronic_document(id),
    previous_status varchar(30),
    new_status varchar(30) not null,
    message varchar(1000),
    actor_user_id bigint references app_user(id),
    occurred_at timestamp with time zone not null default current_timestamp
);

create table fiscal_configuration (
    id bigint generated by default as identity primary key,
    company_id bigint not null references company_profile(id) unique,
    environment varchar(20) not null default 'TEST',
    provider_code varchar(40) not null default 'PENDING',
    endpoint_url varchar(500),
    sol_username_reference varchar(200),
    certificate_reference varchar(500),
    active boolean not null default false,
    updated_at timestamp with time zone not null default current_timestamp
);

create view stock_balance as
select branch_id, product_id, coalesce(sum(quantity), 0) as quantity
from inventory_movement
group by branch_id, product_id;

create index idx_purchase_issue_date on purchase(issue_date);
create index idx_payment_record_sale on payment_record(sale_id);
create index idx_adjustment_original_sale on adjustment_document(original_sale_id);
create index idx_electronic_document_event_document on electronic_document_event(electronic_document_id, occurred_at);

