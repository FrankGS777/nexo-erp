create table company_transport_profile (
 id bigint generated by default as identity primary key,
 company_id bigint not null references company_profile(id),
 profile_name varchar(80) not null,
 transport_mode varchar(20),
 carrier_ruc varchar(11),
 carrier_name varchar(220),
 driver_name varchar(160),
 driver_document varchar(20),
 driver_license varchar(20),
 vehicle_plate varchar(15),
 vehicle_brand varchar(60),
 is_default boolean not null default false,
 active boolean not null default true,
 created_by bigint not null references app_user(id),
 created_at timestamp with time zone not null default current_timestamp,
 updated_at timestamp with time zone not null default current_timestamp,
 unique(company_id, profile_name),
 check(transport_mode is null or transport_mode in ('PRIVADO','PUBLICO'))
);
create index idx_company_transport_profile
 on company_transport_profile(company_id, is_default, active);

create table spring_session (
 primary_id char(36) not null,
 session_id char(36) not null,
 creation_time bigint not null,
 last_access_time bigint not null,
 max_inactive_interval integer not null,
 expiry_time bigint not null,
 principal_name varchar(100),
 constraint spring_session_pk primary key (primary_id)
);
create unique index spring_session_ix1 on spring_session(session_id);
create index spring_session_ix2 on spring_session(expiry_time);
create index spring_session_ix3 on spring_session(principal_name);

create table spring_session_attributes (
 session_primary_id char(36) not null,
 attribute_name varchar(200) not null,
 attribute_bytes bytea not null,
 constraint spring_session_attributes_pk primary key (session_primary_id, attribute_name),
 constraint spring_session_attributes_fk foreign key (session_primary_id)
   references spring_session(primary_id) on delete cascade
);
