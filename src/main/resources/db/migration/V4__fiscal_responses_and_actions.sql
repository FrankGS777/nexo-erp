alter table electronic_document add column cdr_sha256 varchar(64);

create table fiscal_action_request (
    id bigint generated by default as identity primary key,
    electronic_document_id bigint not null references electronic_document(id),
    action_type varchar(30) not null,
    reason varchar(500) not null,
    status varchar(30) not null default 'PENDING',
    provider_ticket varchar(180),
    error_code varchar(60),
    error_message varchar(1000),
    requested_by bigint not null references app_user(id),
    requested_at timestamp with time zone not null default current_timestamp,
    completed_at timestamp with time zone
);

create index idx_fiscal_action_document on fiscal_action_request(electronic_document_id, requested_at);
create index idx_fiscal_action_status on fiscal_action_request(status);
