alter table app_user add column mfa_secret_encrypted varchar(1000);
alter table app_user add column mfa_enrolled_at timestamp with time zone;
alter table app_user add column mfa_last_used_step bigint;
alter table app_user add column mfa_failed_attempts integer not null default 0;
alter table app_user add column mfa_locked_until timestamp with time zone;
alter table app_user add column must_change_password boolean not null default false;
alter table app_user add column password_changed_at timestamp with time zone;

create table mfa_recovery_code (
    id bigint generated by default as identity primary key,
    user_id bigint not null references app_user(id),
    code_hash varchar(255) not null,
    created_at timestamp with time zone not null default current_timestamp,
    used_at timestamp with time zone
);

create index idx_mfa_recovery_user_unused on mfa_recovery_code(user_id, used_at);
